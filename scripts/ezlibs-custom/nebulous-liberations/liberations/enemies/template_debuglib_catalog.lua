return function(EnemyTemplates)
    for alias, style in pairs(ALIASES) do
        local template_name = "DebugProg_" .. alias
        local profile = PROFILES[style]
        local stage = profile.stages[1]
        local effect_root = ROOT .. "attacks/" .. stage.effect
        EnemyTemplates.register(template_name, {
            battle_name = alias, default_ow_bot_encounter_name = "Catalog_" .. alias,
            health = 80, max_health = 80,
            texture_path = PROG, animation_path = PROG_ANIM,
            ai_type = "patterned_attack", attack_profile = profile,
            attack_damage = profile.attack_damage, is_special_encounter = true,
            has_attack_animation = false, shape = {{1}}, shape_offset_y = 0,
            preload_assets = { PROG, PROG_ANIM, effect_root .. ".png", effect_root .. ".animation" },
        })
    end
end
